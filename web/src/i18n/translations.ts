export function translate(
  language: Language,
  key: string,
  values: Record<string, string | number> = {},
): string {
  const template =
    translations[language][key] ?? translations["pt-BR"][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}

const ERROR_KEYS: Record<string, string> = {
  "O nome do baralho não pode ficar vazio": "deckNameRequired",
  "O nome do grupo não pode ficar vazio": "groupNameRequired",
  "A frente do cartão não pode ficar vazia": "frontRequired",
  "O verso do cartão não pode ficar vazio": "backRequired",
  "O cartão já está neste baralho": "cardAlreadyInDeck",
};

export function translateError(language: Language, message: string): string {
  const key = ERROR_KEYS[message];
  return key ? translate(language, key) : message;
}
